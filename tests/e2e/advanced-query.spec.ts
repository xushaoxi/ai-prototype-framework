import {expect,test} from './fixtures';

test('AST-014 已生效筛选、待提交提示与无结果恢复',async({page})=>{
  await page.goto('/#/assets');
  const keyword=page.getByRole('textbox',{name:'关键词',exact:true});
  await keyword.fill('AST-2026-001');
  await page.getByRole('button',{name:'查询',exact:true}).click();
  await expect(page.locator('.applied-filters')).toContainText('关键词：AST-2026-001');
  await keyword.fill('AST-2026-002');
  await expect(page.getByRole('status').filter({hasText:'列表仍显示上次查询结果'})).toBeVisible();
  await page.getByRole('button',{name:'查询',exact:true}).click();
  await expect(page.locator('.applied-filters')).toContainText('关键词：AST-2026-002');
  await keyword.fill('没有这条记录');
  await page.getByRole('button',{name:'查询',exact:true}).click();
  await expect(page.getByText('暂无符合条件的记录',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'清除筛选条件',exact:true}).click();
  await expect(page.getByRole('tab',{name:'全部 36',exact:true})).toBeVisible();
  await expect(page.locator('.applied-filters')).toHaveCount(0);
});

