test('COL-001 损坏或不可写的偏好不会影响本次显示设置',async({page})=>{
  await page.addInitScript(()=>{
    localStorage.setItem('prototype-workbench:columns:v1:assets','invalid-json');
    const original=Storage.prototype.setItem;
    Storage.prototype.setItem=function(key,value){if(key.startsWith('prototype-workbench:columns:'))throw new DOMException('denied','QuotaExceededError');return original.call(this,key,value);};
  });
  await page.goto('/');
  await expect(page.getByRole('columnheader').filter({hasText:'资产金额'})).toBeVisible();
  await page.getByRole('button',{name:'列设置',exact:true}).click();
  await page.locator('.column-settings').getByRole('checkbox',{name:'资产金额',exact:true}).uncheck();
  await expect(page.getByText('调整已生效，但浏览器无法保存本次列设置。',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'列设置',exact:true}).click();
  await expect(page.getByRole('columnheader').filter({hasText:'资产金额'})).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('columnheader').filter({hasText:'资产金额'})).toBeVisible();
});


