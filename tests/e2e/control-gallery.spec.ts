import {test,expect} from './fixtures';
test('CONTROL-GALLERY 选择穿梭、开关滑块与折叠均为可操作示例',async({page})=>{
 await page.goto('/#/component-demo');
 const gallery=page.getByRole('region',{name:'基础控件组合'});
 await expect(gallery).toBeVisible();
 await gallery.getByRole('listitem',{name:'设计说明',exact:true}).getByRole('checkbox').check();
 await gallery.getByRole('button',{name:'移入已选'}).click();
 await expect(gallery.getByRole('status').filter({hasText:'已选资料'})).toContainText('设计说明');
 await gallery.getByRole('switch',{name:'开启通知示例'}).click();
 await expect(gallery.getByRole('status').filter({hasText:'通知状态'})).toContainText('已开启');
 const slider=gallery.getByRole('slider',{name:'完成进度示例'});
 await slider.focus();await slider.press('ArrowRight');
 await expect(gallery.getByRole('status').filter({hasText:'完成进度'})).toContainText('41%');
 await gallery.getByRole('button',{name:'展开使用说明'}).click();
 await expect(gallery.getByText('所有示例仅保留在当前页面，不写入业务数据。',{exact:true})).toBeVisible();
 await gallery.getByRole('switch',{name:'禁用控件示例'}).click();
 await expect(gallery.getByRole('switch',{name:'开启通知示例'})).toBeDisabled();
 await gallery.getByRole('switch',{name:'禁用控件示例'}).click();
 await page.screenshot({path:'/tmp/control-gallery-desktop.png',animations:'disabled'});
 await page.setViewportSize({width:390,height:844});
 await gallery.scrollIntoViewIfNeeded();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'/tmp/control-gallery-mobile.png',animations:'disabled'});
 await gallery.getByPlaceholder('开始日期',{exact:true}).click();
 const datePanel=page.locator('.control-gallery-picker-popup:visible .ant-picker-date-panel-container');
 await expect(datePanel).toBeVisible();
 const dateBox=await datePanel.boundingBox();
 expect(dateBox&&dateBox.x>=0&&dateBox.x+dateBox.width<=390).toBe(true);
 await page.screenshot({path:'/tmp/control-gallery-date-mobile.png',animations:'disabled'});
 await page.keyboard.press('Escape');
 await gallery.getByPlaceholder('开始时间',{exact:true}).click();
 const timePanel=page.locator('.control-gallery-picker-popup:visible .ant-picker-time-panel-container');
 await expect(timePanel).toBeVisible();
 const timeBox=await timePanel.boundingBox();
 expect(timeBox&&timeBox.x>=0&&timeBox.x+timeBox.width<=390).toBe(true);
 await page.screenshot({path:'/tmp/control-gallery-time-mobile.png',animations:'disabled'});
 await page.keyboard.press('Escape');
});
test('CONTROL-GALLERY 搜索、附件元数据与说明浮层可清理',async({page})=>{
 await page.goto('/#/component-demo');
 const gallery=page.getByRole('region',{name:'基础控件组合'});
 await gallery.getByLabel('搜索演示条目').fill('设计');
 await gallery.getByRole('button',{name:'搜索示例'}).click();
 await expect(gallery.getByRole('status').filter({hasText:'搜索结果'})).toContainText('设计');
 await gallery.getByLabel('组织树选择',{exact:true}).click();
 await page.getByText('产品部',{exact:true}).click();
 await gallery.getByLabel('地区级联选择',{exact:true}).click();
 await page.getByText('华东',{exact:true}).click();
 await page.getByText('上海',{exact:true}).click();
 await gallery.getByRole('tab',{name:'活动示例'}).click();
 await expect(gallery.getByText('活动内容：本页演示了标签切换。',{exact:true})).toBeVisible();
 await gallery.locator('input[type=file]').setInputFiles({name:'控件说明.pdf',mimeType:'application/pdf',buffer:Buffer.from('demo')});
 await expect(gallery.getByText('控件说明.pdf',{exact:true})).toBeVisible();
 await gallery.getByRole('button',{name:'删除文件'}).click();
 await expect(gallery.getByText('控件说明.pdf',{exact:true})).toHaveCount(0);
 await gallery.getByRole('button',{name:'查看浮层说明'}).click();
 await expect(page.getByText('这是可关闭的本地说明浮层。',{exact:true})).toBeVisible();
});
