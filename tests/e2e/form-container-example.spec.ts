  await page.getByRole('button',{name:'新增示例资产',exact:true}).click();
  const modal=page.getByRole('dialog',{name:'新增示例资产',exact:true});
  await expect(modal).toBeVisible();
  await expect(modal.getByText('带 * 的为必填项',{exact:true})).toBeVisible();
  await expect(modal.getByLabel('资产名称',{exact:true})).toHaveAttribute('aria-required','true');
  await expect(modal.getByLabel('备注',{exact:true})).not.toHaveAttribute('aria-required','true');
  await expect(modal.locator('.ant-form-item-optional')).toHaveCount(0);
  await expect(modal.locator('.ant-form-item-explain-error')).toHaveCount(0);
  await page.screenshot({path:'test-results/form-container-modal-desktop.png',fullPage:true,animations:'disabled'});
  await modal.getByRole('button',{name:'保存示例',exact:true}).click();
