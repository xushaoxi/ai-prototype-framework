import {test,expect} from './fixtures';
import {STORAGE_KEY} from '../../src/core/storage-key';
import {createSeed} from '../../src/mocks/seed';

test('AST-015 旧金额只聚焦再离开输入框不会被自动舍入',async({page})=>{
  const snapshot=createSeed();snapshot.records.assets[0].amount=12.345;
  await page.addInitScript(({key,data})=>localStorage.setItem(key,JSON.stringify(data)),{key:STORAGE_KEY,data:snapshot});
  await page.goto('/#/assets');
  await page.getByRole('textbox',{name:'关键词',exact:true}).fill('AST-2026-001');
  await page.getByRole('button',{name:'查询',exact:true}).click();
  await page.getByRole('row').filter({hasText:'AST-2026-001'}).getByRole('button',{name:'编辑',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'编辑资产',exact:true});
  const amount=dialog.getByLabel('资产金额',{exact:true});
  await expect(amount).toHaveValue('12.345');
  await amount.click();
  await dialog.getByLabel('负责人',{exact:true}).click();
  await dialog.getByRole('button',{name:'保存',exact:true}).click();
  await expect(dialog).toBeHidden();
  expect(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)!).records.assets[0].amount,STORAGE_KEY)).toBe(12.345);
  await page.getByRole('row').filter({hasText:'AST-2026-001'}).getByRole('button',{name:'编辑',exact:true}).click();
  await amount.fill('13.456');
  await dialog.getByRole('button',{name:'保存',exact:true}).click();
  await expect(dialog.getByText('资产金额最多保留2位小数',{exact:true})).toBeVisible();
  await amount.fill('13.45');
  await dialog.getByRole('button',{name:'保存',exact:true}).click();
  await expect(dialog).toBeHidden();
  expect(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)!).records.assets[0].amount,STORAGE_KEY)).toBe(13.45);
});

